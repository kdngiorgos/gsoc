function stripPrefix(code: string): string {
  // Remove leading "NN-" section prefix (e.g. "00-" or "15-")
  return code.replace(/^\d{2}-/, "");
}

export function kaeLabel(code: string): string {
  const stripped = stripPrefix(code);

  // Exact match
  if (KAE_MAP[stripped]) return KAE_MAP[stripped];

  // 4-char prefix (e.g. "6031" from "6031.001")
  const four = stripped.slice(0, 4);
  if (KAE_MAP[four]) return KAE_MAP[four];

  // 3-char prefix
  const three = stripped.slice(0, 3);
  if (KAE_MAP[three]) return KAE_MAP[three];

  // 2-char prefix
  const two = stripped.slice(0, 2);
  if (KAE_MAP[two]) return KAE_MAP[two];

  // No match — return original
  return code;
}
